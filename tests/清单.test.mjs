/**
 * `lib/清单.mjs` 的判据。挑的口子是**错了会不会静默** ——
 * 这个模块的每一种错都长得像"正常"：进度停着不动、漏项不报、超时照旧只回一句「卡住了」。
 */
import { 建清单 } from '../lib/清单.mjs';

let 挂 = 0, n = 0;
const 真 = (ok, 说) => { n++; if (ok) console.log(`✓ ${说}`); else { 挂++; console.log(`✗ ${说}`); } };
const eq = (a, b, 说) => 真(JSON.stringify(a) === JSON.stringify(b), `${说}${JSON.stringify(a) === JSON.stringify(b) ? '' : `｜得 ${JSON.stringify(a)} 期 ${JSON.stringify(b)}`}`);

// —— 记下 + 进度 ——
{
  const c = 建清单();
  真(!c.有吗(), '空清单：有吗() 是 false（没条目时别给人看一个 0/0）');
  eq(c.进度文(), '', '空清单：进度文是空串，不是「0/0」');
  eq(c.交半份(), '', '空清单：交半份回空串 —— 调用方好退回原来那句话');

  eq(c.记下(['查内存 128G', '查系统盘 960G', '查网卡']), { 新增: 3, 共: 3 }, '记下：三条都进去了');
  eq(c.进度(), { 做完: 0, 共: 3 }, '记下：刚记完一条都没做完');
  eq(c.进度文(), '｜清单 0/3', '进度文：给卡片用的一小段');
}

// —— 再次记下是「合并」不是「重来」 ——
// 覆盖式的话进度会倒退，人看着像机器在返工，而且勾过的状态无声地没了。
{
  const c = 建清单();
  c.记下(['A', 'B']);
  c.勾掉([1], '查到了');
  const r = c.记下(['A', 'B', 'C']);          // 模型中途想起还有 C，重列一遍
  eq(r, { 新增: 1, 共: 3 }, '再次记下：只新增没见过的那条（A/B 按文去重）');
  eq(c.进度(), { 做完: 1, 共: 3 }, '再次记下：**A 的勾没被抹掉**（覆盖式会让进度倒退）');
  eq(c.条目们()[0].结果, '查到了', '再次记下：老条目的结果也留着');
}

// —— 勾掉：越界必须报出来 ——
// 静默忽略的话，「模型勾错号」和「这条真办完了」长得一模一样，进度永远停着、什么都不红。
{
  const c = 建清单();
  c.记下(['A', 'B']);
  const r = c.勾掉([1, 5, 0, 'x'], '结果一');
  eq(r.勾掉了, [1], '勾掉：合法的那个勾上了');
  eq(r.越界, [5, 0, 'x'], '勾掉：**越界/非法的原样报回去**，不许静默吞掉');
  eq(r.做完, 1, '勾掉：返回值带上当下进度');
  eq(c.条目们()[0].结果, '结果一', '勾掉：结果记在那一条上');
  eq(c.条目们()[1].做完, false, '勾掉：没点到的那条不受影响（只验一边等于没验）');
}

// —— 漏了吗：交卷前自查 ——
{
  const c = 建清单();
  c.记下(['查内存', '查硬盘', '查网卡']);
  真(c.漏了吗().includes('3 项'), '漏了吗：一条没做时报 3 项');
  c.勾掉([1, 2]);
  const 话 = c.漏了吗();
  真(话.includes('1 项') && 话.includes('查网卡'), '漏了吗：**点名是哪一项**没做（只报个数人还得自己数）');
  真(话.includes('明说'), '漏了吗：给出路——要么查完要么明说没查，不许当它不存在');
  c.勾掉([3]);
  eq(c.漏了吗(), '', '漏了吗：全做完回空串（全绿时别刷一行噪音）');
}

// —— 交半份：这是这个模块存在的头号理由 ——
// 没有它，撞硬顶的查询只回一句「卡住了」，前面几步查到的东西一个字都不给人。
{
  const c = 建清单();
  c.记下(['增配内存 128G ×188', '减配系统盘 3.84T', '增配系统盘 960G ×36']);
  c.勾掉([1], '移动7号楼 2623 够');
  c.勾掉([2], '拆除项，不查库存');
  const 半 = c.交半份();
  真(半.includes('3 项做完 2 项'), '交半份：报「共几项、做完几项」');
  真(半.includes('✅') && 半.includes('移动7号楼 2623 够'), '交半份：**做完的那几项带结果原样给人**');
  真(半.includes('⬜') && 半.includes('增配系统盘 960G ×36'), '交半份：没做的那项明说没查到（别假装它不存在）');
  // 反向：全做完的时候这段话也得成立（不然只在"半途"这一种情形下被验过）
  c.勾掉([3], '闵行够');
  真(c.交半份().includes('3 项做完 3 项') && !c.交半份().includes('⬜'),
    '交半份：全做完时没有 ⬜ 那一行');
}

console.log(`\n检查了 ${n} 条判据，失败 ${挂}`);
process.exit(挂 ? 1 : 0);
