/**
 * 例行更新（日更/周更/导工单）的纯逻辑。**最要紧的一条是「模型编出来的键一律丢掉」** ——
 * `认定的改名` 直接决定哪两个物料键被合并，而合并错了改不回来，
 * 且回执照样成句、数字照样有，**没有任何东西会红**。
 *
 * 样本抄自 2026-08-24 真跑的干跑回包（日更和周更各一次），不是我编的形状。
 * 只认返回值、不打网、不调 MCP。
 */
import { 例行们, 认例行口令, 认例行近似, 解干跑, 改名提示, 认改名判断, 回执正文, 解定时, 该跑吗, 定时说法 } from '../lib/例行更新.mjs';

let 挂 = 0, n = 0;
const eq = (得, 期, 说) => { n++; if (JSON.stringify(得) !== JSON.stringify(期)) { 挂++; console.log(`✗ ${说}｜得 ${JSON.stringify(得)} 期 ${JSON.stringify(期)}`); } else console.log(`✓ ${说}`); };
const 真 = (得, 说) => eq(!!得, true, 说);

// 真实干跑回包（2026-08-24 日更）
const 真回包 = JSON.stringify({
  干跑: true, 待确认: true, 确认票: 'dcd939ee-2f81-444f-ad14-73ad7018b890',
  回执: {
    数据日期: '2026-08-24',
    台账: '现有 406 条 → 新增 4 · 更新 37 · 置0 6 · 不变 332',
    注册表: '条目 381→381（本次新发 4 键）',
    在途: '还剩 0 条没挂真键',
  },
  干跑自检红: [],
  疑似改名: [{
    序号: 1,
    新键: '光模块|H3C|SFP-25G-LR-UPC|临港9号楼',
    最像的老键: '光模块|H3C|SFP-25G-LR-SM1310|临港9号楼',
    老键原在库: 23,
    差在哪: ['核心槽位完全相同'],
    接头尾巴: '老 [] / 新 ["UPC"]',
  }],
});

// —— 三件例行公事的声明本身 ——
{
  eq(Object.keys(例行们).sort(), ['周更', '导工单', '日更'], '三件都在');
  for (const [名, 配] of Object.entries(例行们)) {
    真(配.干跑毫秒 > 45000, `${名} 的干跑超时 > 45 秒 —— **默认那道闸就是 45 秒**，不放宽必翻车`);
    真(配.真写毫秒 >= 配.干跑毫秒, `${名} 的真写超时不小于干跑（真写比干跑还慢）`);
    真(配.前缀 && 配.工具 && 配.名, `${名} 三个必要字段齐`);
  }
  eq(例行们.导工单.判改名, false, '**导工单不判改名** —— 它的 schema 里根本没有 认定的改名，多塞会被拒');
  eq(例行们.导工单.要内网, true, '导工单要内网（在家跑不了，得在提示里说清）');
}

// —— 口令：**别把问话认成命令**（认错了平白跑 30 秒还写一张确认卡）——
{
  eq(认例行口令('日更')?.名, '日更', '「日更」');
  eq(认例行口令('跑日更')?.名, '日更', '「跑日更」');
  eq(认例行口令('更新台账')?.名, '日更', '「更新台账」');
  eq(认例行口令('周更')?.名, '周更', '「周更」');
  eq(认例行口令('周报')?.名, '周更', '「周报」');
  eq(认例行口令('导工单')?.名, '导工单', '「导工单」');
  eq(认例行口令('同步工单')?.名, '导工单', '「同步工单」');
  eq(认例行口令('日更了吗'), null, '**「日更了吗」是问话，不是命令**');
  eq(认例行口令('周更是什么'), null, '「周更是什么」是问话');
  eq(认例行口令('帮我看下日更的结果'), null, '带别的字的一律不认');
  eq(认例行口令('更新下我的台账看有啥新到库的'), null, '**这就是 8-24 那句真实问话，绝不能被认成命令**');
  eq(认例行口令('导工单要多久'), null, '「导工单要多久」是问话');
}

// —— 解干跑 ——
{
  const r = 解干跑(真回包);
  真(r, '真实回包解得开');
  eq(r.确认票, 'dcd939ee-2f81-444f-ad14-73ad7018b890', '确认票原样取出来（人点确认时要拿它重调，改一个字就废了）');
  eq(解干跑('不是 JSON'), null, '解不开返回 null —— 调用方要把原文摆出来，不许装作没事');
  eq(解干跑('{"回执":{}}'), null, '**没有确认票就不算干跑成功**（没票的话第二步根本写不了）');
  eq(解干跑('{"确认票":"x","回执":"不是对象"}').回执, {}, '回执不是对象时退成空对象，不让下游炸');
  eq(解干跑(null), null, '空的返回 null');
}

// —— 认改名判断：**这个模块的核心安全判据** ——
{
  const 候选 = JSON.parse(真回包).疑似改名;
  const 对的一组 = [{ 新键: '光模块|H3C|SFP-25G-LR-UPC|临港9号楼', 老键: '光模块|H3C|SFP-25G-LR-SM1310|临港9号楼' }];

  eq(认改名判断('{"判断":[{"第几组":1,"同款":true,"理由":"只差接头研磨代号"}]}', 候选).认定的改名, 对的一组, '判同款 → 进 认定的改名');
  eq(认改名判断('好的：\n```json\n{"判断":[{"第几组":1,"同款":true,"理由":"x"}]}\n```', 候选).认定的改名, 对的一组,
    '模型爱裹围栏和废话 —— 照样抠得出来');
  eq(认改名判断('{"判断":[{"第几组":1,"同款":true,"新键":"光模块|H3C|我编的|闵行","老键":"光模块|H3C|也编的|闵行"}]}', 候选).认定的改名, 对的一组,
    '**键取自候选、不取自模型** —— 模型另写一对键，一个字都不许进');
  eq(认改名判断('{"判断":[{"第几组":99,"同款":true}]}', 候选).认定的改名, [], '**候选里没有的组号 → 丢掉**');
  真(认改名判断('{"判断":[{"第几组":99,"同款":true}]}', 候选).丢掉的.length > 0, '丢掉的要报出来（静默丢弃=人以为判过了）');
  eq(认改名判断('{"判断":[]}', 候选).认定的改名, [], '**模型漏判 → 按不合并**');
  真(/模型没判/.test(认改名判断('{"判断":[]}', 候选).判断[0].理由), '漏判的那组照样上卡片，标明是模型没判');
  eq(认改名判断('整个答跑题了', 候选).认定的改名, [], '**没给 JSON → 一个都不合并**（默认必须站保守那边）');
  eq(认改名判断('{"判断":[{"第几组":1,"同款":"true"}]}', 候选).认定的改名, [], '同款是字符串不是布尔 → 不算同款');
  eq(认改名判断('{}', []).认定的改名, [], '没有疑似改名时是空数组（不是省略 —— 省略会被 MCP 拒写）');
}

// —— 改名提示 ——
{
  const p = 改名提示(JSON.parse(真回包).疑似改名);
  真(p.includes('SFP-25G-LR-UPC'), '提示里有新键');
  真(p.includes('23'), '提示里有「老键原在库 23 根」');
  真(p.includes('绝不合并'), '**「速率/光学标准/通道数不同→绝不合并」这条硬判据在提示里**');
  真(p.includes('只输出 JSON'), '要求只输出 JSON');
}

// —— 回执正文：**字段整个遍历，不写死字段名** ——
{
  const r = 解干跑(真回包);
  const 判 = 认改名判断('{"判断":[{"第几组":1,"同款":true,"理由":"只差接头研磨代号"}]}', r.疑似改名).判断;
  const 文 = 回执正文(r, 判, { 名: '日更' });
  真(文.includes('新增 4 · 更新 37 · 置0 6'), '**台账那行是原文，没被转述**');
  真(文.includes('23'), '老键原在库的根数在卡上 —— 人靠这个数拍板');
  真(文.includes('改不回来'), '「合并错了改不回来」这句在卡上');
  真(回执正文(r, 判, { 定时: true, 名: '日更' }).includes('今天的日更'), '定时那条开头不一样（人要分得清是它自己跑的还是我点的）');

  // ★ 周更比日更多五个回执字段。写死字段名的话它们会**静默看不见**
  const 周 = 解干跑(JSON.stringify({
    确认票: 'x',
    回执: { 数据日期: '2026-08-24', 周环比: '出库 20106 / 入库 21010', 品牌待补: '3 个键没品牌', 基线: '上周四 2026-08-20', 源表: '31 张', 缺表: '无' },
  }));
  const 周文 = 回执正文(周, [], { 名: '周更' });
  for (const k of ['周环比', '品牌待补', '基线', '源表', '缺表']) {
    真(周文.includes(k), `周更多出来的「${k}」也上了卡 —— 写死字段名的话这个会静默丢掉`);
  }
  真(回执正文({ 回执: {}, 疑似改名: [], 干跑自检红: [] }, [], { 名: '日更' }).includes('回执是空的'),
    '**回执是空的要说出来**（空回执配一个「确认写入」按钮，是这一整套里最危险的形状）');
}

// —— 定时：天 + 周 ——
{
  eq(解定时('09:00'), [{ 时: 9, 分: 0 }], '每天一个点');
  eq(解定时('09:00,17:30'), [{ 时: 9, 分: 0 }, { 时: 17, 分: 30 }], '每天两个点');
  eq(解定时('四 09:00'), [{ 星期: 4, 时: 9, 分: 0 }], '**每周四**（周更只能周四跑，它和上周四那份基线比）');
  eq(解定时('日 08:00'), [{ 星期: 0, 时: 8, 分: 0 }], '周日=0');
  eq(解定时(''), [], '没配 = 不定时（口令那条路照样能用）');
  eq(解定时('25:00'), [], '不合法的小时丢掉');
  eq(解定时('八 09:00'), [], '没有「星期八」');
  eq(解定时('09:00,乱写'), [{ 时: 9, 分: 0 }], '一个对一个错，只留对的');
  真(定时说法(解定时('四 09:00')).includes('每周四'), '说法给人看得懂的（帮助卡和开机日志都用它）');
  真(定时说法(解定时('09:00')).includes('每天'), '每天那种说「每天」');

  const 天 = 解定时('09:00');
  eq(该跑吗(new Date(2026, 7, 24, 9, 0, 30), 天, new Set()), '2026-08-24 09:00', '到点了就跑');
  eq(该跑吗(new Date(2026, 7, 24, 8, 59, 0), 天, new Set()), null, '没到点不跑');
  eq(该跑吗(new Date(2026, 7, 24, 9, 0, 30), 天, new Set(['2026-08-24 09:00'])), null, '**今天这个点跑过了就不再跑**');
  eq(该跑吗(new Date(2026, 7, 25, 9, 0, 30), 天, new Set(['2026-08-24 09:00'])), '2026-08-25 09:00', '第二天照跑');
  eq(该跑吗(new Date(2026, 7, 24, 9, 45, 0), 天, new Set()), '2026-08-24 09:00', '睡过去几十分钟，醒来还补跑');
  eq(该跑吗(new Date(2026, 7, 24, 15, 0, 0), 天, new Set()), null, '**超过一小时不补跑** —— 数据早变了');

  // 2026-08-27 是周四
  const 周四 = 解定时('四 09:00');
  eq(new Date(2026, 7, 27).getDay(), 4, '（先确认 2026-08-27 真是周四，不然下面两条判的是别的东西）');
  eq(该跑吗(new Date(2026, 7, 27, 9, 0, 30), 周四, new Set()), '2026-08-27 09:00', '周四到点跑');
  eq(该跑吗(new Date(2026, 7, 26, 9, 0, 30), 周四, new Set()), null, '**周三不跑**（周更只能周四）');
  eq(该跑吗(new Date(2026, 7, 28, 9, 0, 30), 周四, new Set()), null, '周五也不跑');
}

/*
 * —— 认例行近似：**说得像但没打准**（弹按钮，不直接跑）——
 *
 * 2026-08-24 真事：「执行下日更然后哪些能合并老键哪些不能合并下说下」落给了模型，
 * 它拿只读工具东拼西凑答一段大表格、撞了两次 max_tokens 截断、还撒谎说自己没有日更工具。
 * 判据：说得出名字的话要能认出来；纯问句、追问、不相关的话绝不能被当成命令去弹按钮
 * （弹错了也是打扰，虽然比直接跑安全）。
 */
{
  eq(认例行近似('执行下日更然后哪些能合并老键哪些不能合并下说下')?.名, '日更', '**这就是 8-24 那句真实话，必须认出「日更」**');
  eq(认例行近似('日更下台账')?.名, '日更', '「日更下台账」');
  eq(认例行近似('帮我跑个日更')?.名, '日更', '「帮我跑个日更」');
  eq(认例行近似('周更一下呗')?.名, '周更', '「周更一下呗」—— 带「呗」这种语气词也要认出来');
  eq(认例行近似('麻烦导工单')?.名, '导工单', '「麻烦导工单」');
  eq(认例行近似('更新一下台账')?.名, '日更', '没直呼其名，「更新」+「台账」也认得出');
  eq(认例行近似('跑个台账更新')?.名, '日更', '「跑个台账更新」');

  eq(认例行近似('日更了吗'), null, '**「日更了吗」是问话，不弹按钮**（强口令那条已经不认它，这条也不能捡回来）');
  eq(认例行近似('日更是什么'), null, '「日更是什么」是问话');
  eq(认例行近似('日更要多久'), null, '「日更要多久」');
  eq(认例行近似('上次日更结果呢'), null, '带「上次」「结果」的追问，不是要求现在跑');
  eq(认例行近似('周更能不能加个字段'), null, '带「能不能」的建议/问题，不是命令');
  eq(认例行近似('导工单是干什么用的'), null, '「导工单是干什么用的」');
  eq(认例行近似('重来'), null, '和三件事完全无关的话');
  eq(认例行近似('新增的键说下，老的没有吗'), null, '追问细节，不含任何一件的名字');
  eq(认例行近似(''), null, '空字符串');
  eq(认例行近似('日更'), null, '**已经是强口令能认出来的，这条不重复认**（认例行口令 会先接住，两条判据不重叠）');
  eq(认例行近似('把今天所有日更周更导工单的事都说一遍这句话故意写得很长超过三十个字看它认不认'), null,
    '**超长的话不认**（那不像一句下命令的话，多半是别的意图裹带了这个词）');
}

console.log(`\n检查了 ${n} 条判据，失败 ${挂}`);
process.exit(挂 ? 1 : 0);
