// —— 建刷：节流 + 作废闸（正反双向：作废前刷得动，作废后一律刷不动）——
{
  let 钟 = 0; const 刷到的 = [];
  const 停 = new AbortController();
  const 刷 = 建刷((md) => 刷到的.push(md), { 节流毫秒: 600, signal: 停.signal, 现在: () => 钟 });
  真(刷('a'), '刷卡：第一次直接刷');
  eq(刷('b'), false, '刷卡：600ms 内的第二次被节流丢掉');
  钟 = 600;
  真(刷('c'), '刷卡：过了节流窗能刷');
  eq(刷到的.join(','), 'a,c', '刷卡：只有该刷的那两条真到了卡片');
  停.abort(); 钟 = 5000;
  eq(刷('d'), false, '刷卡：作废之后一律不刷（超时提示不会被半截答案盖回去）');
  eq(刷到的.length, 2, '刷卡：作废后一条都没再发出去');
}

