// —— 建看门狗：卡住必死、干得久但一直有进展不许死、停了不许再响（用小数值跑真定时器）——
{
  // ① 不喂 → 空闲判死
  let 因 = null;
  建看门狗({ 空闲毫秒: 80, 硬顶毫秒: 5000, 到期: (x) => { 因 = x; } });
  await 等(200);
  真(因 && /没有任何进展/.test(因), `看门狗：卡住不动 → 空闲判死（「${因}」）`);

  // ② 一直喂 → 撑过空闲窗不死（54 秒的对账正在吐字，不该被杀）
  因 = null;
  const w = 建看门狗({ 空闲毫秒: 80, 硬顶毫秒: 100000, 到期: (x) => { 因 = x; } });
  for (let i = 0; i < 6; i++) { await 等(40); w.喂(); }   // 240ms 里一直有进展，是空闲窗的 3 倍
  eq(因, null, '看门狗：一直有进展 → 撑过空闲窗不判死（54 秒的对账不该被杀）');
  w.停();

  // ③ 但喂得再勤也顶不过硬顶（防真死循环）
  因 = null;
  const w2 = 建看门狗({ 空闲毫秒: 100000, 硬顶毫秒: 200, 到期: (x) => { 因 = x; } });
  for (let i = 0; i < 12 && !因; i++) { await 等(40); w2.喂(); }
  真(因 && /硬顶/.test(因), `看门狗：喂再勤也顶不过硬顶（「${因}」）`);
  w2.停();

  // ③ 停了之后不许再响（查询正常结束后不能再往用户脸上写超时）
  因 = null;
  建看门狗({ 空闲毫秒: 60, 硬顶毫秒: 5000, 到期: (x) => { 因 = x; } }).停();
  await 等(150);
  eq(因, null, '看门狗：停了之后不再回调');
}

