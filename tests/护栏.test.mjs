// —— 该理会吗：判据是「@ 的是不是它自己」，不是「有没有人被 @」——
//
// 2026-08-24 修了两次。第一版写的是「mentions 非空就理」，而群里同事互相 @ 是常事 ——
// 真事：「@邓老师，明天纪老师要的 2+80 台…」这句 @ 的是**人**，机器人以为在叫它，
