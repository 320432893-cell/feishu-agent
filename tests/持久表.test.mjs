/**
 * 持久表测试。守的核心是**重启之后票还在**——原来三张 Map 一重启就没，
 * 而人对着「确认写入」的卡片点下去，群里一个字都不会出现。
 * 「重启」在这里用「重新建一次表」模拟（同一个文件，新的内存对象）。只认退出码、不打网。
 */
import { mkdtempSync, rmSync, chmodSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { 建持久表 } from '../lib/持久表.mjs';

const 临 = mkdtempSync(join(tmpdir(), 'bot-state-'));
let 挂 = 0, n = 0;
const eq = (得, 期, 说) => { n++; if (JSON.stringify(得) !== JSON.stringify(期)) { 挂++; console.log(`✗ ${说}｜得 ${JSON.stringify(得)} 期 ${JSON.stringify(期)}`); } else console.log(`✓ ${说}`); };
const 真 = (得, 说) => eq(!!得, true, 说);

const 建 = (名 = '写入票', 存活毫秒 = 900000) => 建持久表(名, { 存活毫秒, 目录: 临 });

// —— 重启后还在（这个模块的全部意义）——
{
  const a = 建();
  a.set('票1', { 工具名: '写占用', 参数: { 工单号: '31796' }, sender: 'ou_甲', ts: Date.now() });
  eq(a.状态().现有, 1, '存：进得去');

  const b = 建(); // ← 模拟重启：全新的内存对象，同一个文件
  真(b.get('票1'), '**重启后票还在**（原来这里是 undefined，人点按钮群里没反应）');
  eq(b.get('票1').参数.工单号, '31796', '重启后参数原样带回来（真执行时用的就是这份）');
  eq(b.get('票1').sender, 'ou_甲', '重启后发起人还在（「只有发起人能点」这道校验才守得住）');
  eq(b.状态().开机读回, 1, '状态()报得出开机读回几条 —— 0 或偏小=没读到，不是没票');
}

// —— 一次性：删了就真没了，重启也不许复活（复活=同一张票能写两次）——
{
  const a = 建();
  a.delete('票1');
  eq(a.get('票1'), undefined, '删：当场就没了');
  const b = 建();
  eq(b.get('票1'), undefined, '**删过的票重启后不许复活**（复活=同一笔写入能提交两次）');
  eq(b.状态().开机读回, 0, '删完文件里确实空了');
}

// —— 过期：读的时候判，不靠定时器（定时器停了会让过期数据复活）——
{
  const a = 建('澄清票', 1000);
  a.set('旧', { 问: '很久以前问的', ts: Date.now() - 5000 });
  a.set('新', { 问: '刚问的', ts: Date.now() });
  // 先重启再读：get 过期条目时会顺手把它删掉并落盘，先读的话文件里就没有过期条目可丢了
  const b = 建('澄清票', 1000);
  eq(b.状态().开机读回, 1, '过期：开机只读回没过期的那条');
  eq(b.状态().开机丢弃, 1, '过期：丢了几条也报出来（不然「清干净了」和「压根没读」一样）');
  eq(a.get('旧'), undefined, '过期：超过存活期的读不回来');
  真(a.get('新'), '过期：没到期的照常读得回来');
}

// —— 迭代顺手清过期（原来 bot 里那几处「惰性清过期」的 for 循环）——
{
  const a = 建('上下文', 1000);
  a.set('甲', { 历史: [], ts: Date.now() - 9999 });
  a.set('乙', { 历史: [], ts: Date.now() });
  eq([...a].map(([k]) => k), ['乙'], '迭代：过期的当场清掉，只剩活的');
  eq(a.size, 1, '迭代：清完 size 也对');
}

// —— 写不进去：不许炸掉查询，但**必须能被看见** ——
{
  const 只读目录 = join(临, '只读');
  mkdirSync(只读目录, { recursive: true });
  const c = 建持久表('票', { 存活毫秒: 900000, 目录: 只读目录 });
  chmodSync(只读目录, 0o500); // 进得去、写不了
  let 炸了 = false;
  try { c.set('票9', { ts: Date.now() }); } catch { 炸了 = true; }
  eq(炸了, false, '写不进去：**不许把查询带崩**（落盘失败只是回到「重启就丢」）');
  真(c.状态().写不进去, '写不进去：**状态里挂着原因** —— 不然这个模块坏掉之后和好着的时候长得一样');
  真(c.get('票9'), '写不进去：内存里那份照常能用，这一轮不受影响');
  chmodSync(只读目录, 0o700);
}

// —— 坏文件不许让整张表读不回来（写到一半断电）——
{
  writeFileSync(join(临, '半个.json'), '{"票1": {"ts": 17');
  const d = 建持久表('半个', { 存活毫秒: 900000, 目录: 临 });
  eq(d.状态().现有, 0, '坏文件：当空表处理，不抛');
  d.set('新票', { ts: Date.now() });
  eq(建持久表('半个', { 存活毫秒: 900000, 目录: 临 }).状态().开机读回, 1, '坏文件：写一次就修好了');
  真(!readFileSync(join(临, '半个.json'), 'utf8').includes('票1'), '坏文件：旧的半截内容被整个盖掉，没有和新内容拼在一起');
}

// —— 键里有特殊字符（上下文的键是 `chat|sender`）——
{
  const a = 建('上下文2', 900000);
  a.set('oc_abc|ou_甲', { 历史: [{ role: 'user', content: '有"引号"和\n换行' }], ts: Date.now() });
  const b = 建('上下文2', 900000);
  eq(b.get('oc_abc|ou_甲').历史[0].content, '有"引号"和\n换行', '键和值里的特殊字符原样往返');
}

// —— 清过期()：bot 里三处「惰性清过期」现在调的就是它 ——
{
  const a = 建('清一清', 1000);
  a.set('旧1', { ts: Date.now() - 9999 });
  a.set('旧2', { ts: Date.now() - 9999 });
  a.set('新', { ts: Date.now() });
  eq(a.清过期(), 2, '清过期：**返回清了几条** —— 0 或偏小=没清到，不是没有过期的');
  eq(a.size, 1, '清过期：只剩没过期的');
  eq(a.清过期(), 0, '清过期：再清一次是 0（幂等）');
}

/*
 * —— 每张建出来的表都得进开机日志那一行 ——
 *
 * 2026-08-23 真踩到：表从三张长到六张，而开机那个 `for (const 表 of [...])` 还是最早那三张，
 * 后加的三张**写不进去时一个字都不打**。那一行是「持久化真的在工作」的唯一证据，
 * 漏一张 = 那张表悄悄退回「重启就丢」而没人会发现 —— 正是这个项目一直在抓的「坏了却是绿的」。
 *
 * 靠纪律记不住，所以在这儿对一遍源码：`建持久表('X'` 的名字集合，必须等于日志循环数组里的变量名集合。
 * **不读退出码读名字**：数量对不上要说出差的是哪张，不然报红了还得自己去数。
 */
{
  const 源 = readFileSync(new URL('../bot.mjs', import.meta.url), 'utf8');
  const 建了 = [...源.matchAll(/const (\S+) = 建持久表\(/g)].map((m) => m[1]);
  const 循环 = 源.match(/for \(const 表 of \[([^\]]+)\]\)/);
  真(建了.length >= 6, `扫到 ${建了.length} 张 建持久表(...) —— 明显偏小就是正则没匹配上，不是真只有这么几张`);
  真(循环, '找得到开机日志那个 for 循环 —— 找不到说明它被改写了，这条判据当场失效，得跟着改');
  const 打了 = (循环?.[1] || '').split(',').map((s) => s.trim()).filter(Boolean);
  const 漏的 = 建了.filter((名) => !打了.includes(名));
  eq(漏的, [], `**每张表都进了开机日志**（漏的话这里列出名字：${建了.join('/')}）`);
}

rmSync(临, { recursive: true, force: true });
console.log(`\n检查了 ${n} 条判据，失败 ${挂}`);
process.exit(挂 ? 1 : 0);
