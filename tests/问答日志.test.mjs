/**
 * 问答留存测试：写得进、读得回、**坏了不许把查询带崩**。只认退出码，不打网。
 * 最后一条是重点：留存是辅助设施，它自己出问题时必须安静地失败，而不是让人查不到货。
 */
import { mkdtempSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const 临 = mkdtempSync(join(tmpdir(), 'bot-qa-'));
process.env.BOT_QA_LOG_DIR = 临;
const { 记一条, 读一月 } = await import('../lib/问答日志.mjs');

let 挂 = 0, n = 0;
const 真 = (得, 说) => { n++; if (!得) { 挂++; console.log(`✗ ${说}`); } else console.log(`✓ ${说}`); };
const eq = (得, 期, 说) => { n++; if (得 !== 期) { 挂++; console.log(`✗ ${说}｜得 ${JSON.stringify(得)} 期 ${JSON.stringify(期)}`); } else console.log(`✓ ${说}`); };

记一条({ chat: 'oc_x', sender: 'ou_y', 问: '光模块还有多少', 模型: 'GLM-5.2', 用了: ['查库存'], 轮数: 2, 模型毫秒: 1700, 工具毫秒: 20, 总毫秒: 1750, 收敛: true, 答: '闵行 85093 根' });
记一条({ chat: 'oc_x', sender: 'ou_y', 问: '在库的呢', 出错: '查得太久了', 总毫秒: 45000 });

const 条 = 读一月();
eq(条.length, 2, '写两条读回两条');
eq(条[0].问, '光模块还有多少', '问题原样存下来');
eq(条[0].用了.join(','), '查库存', '用了哪些工具存下来');
eq(条[0].模型毫秒, 1700, '耗时拆分存下来（这是下一轮优化的依据）');
真(条[0].时刻 && /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(条[0].时刻), `时刻是本地时间格式（${条[0].时刻}）`);
eq(条[1].出错, '查得太久了', '出错的那条也记');

// 答案只留摘要 + 长度，不留全文
{
  const 长答 = 'X'.repeat(500);
  记一条({ 问: 'q', 答: 长答 });
  const 最后 = 读一月().pop();
  eq(最后.答长, 500, '答案长度记下来');
  真(最后.答.length <= 121, `答案只留前 120 字（实际 ${最后.答.length}）`);
}

// —— 重点：留存坏了不许影响主流程 ——
{
  const 坏目录 = join(临, '不可写');
  mkdirSync(坏目录, { recursive: true });
  writeFileSync(join(坏目录, `${new Date().toISOString().slice(0, 7)}.jsonl`), 'x');
  process.env.BOT_QA_LOG_DIR = '/dev/null/根本不存在的路径';
  const { 记一条: 记2 } = await import('../lib/问答日志.mjs?坏路径=1');
  let 崩 = false;
  try { 记2({ 问: '写不进去也不许崩' }); } catch { 崩 = true; }
  真(!崩, '目录写不进去时：安静失败，不抛异常（查询不该被留存拖崩）');
  process.env.BOT_QA_LOG_DIR = 临;
}

rmSync(临, { recursive: true, force: true });
// —— 「我问过什么」：记录一直在存，但在这之前只有能 ssh 上机器的人 grep 得到 ——
// **最要紧的一条是「只回自己的」**：所有人的问答在同一个文件里，
// 不按人切的话，一句「老王问过什么」就能把别人的全翻出来。这是边界不是省事。
{
  const { 我问过 } = await import('../lib/问答日志.mjs');
  记一条({ sender: 'ou_甲', 问: '光模块还有多少', 答: '闵行 85093 根', 用了: ['查库存'], 总毫秒: 3200 });
  记一条({ sender: 'ou_乙', 问: '乙问的机密问题', 答: '乙的答案' });
  记一条({ sender: 'ou_甲', 问: '通算多少台', 出错: '连不上内网CMDB' });
  记一条({ sender: 'ou_甲', 类型: '反馈', 反馈: '好' });          // 操作记录，没有「问」
  记一条({ sender: 'ou_甲', 问: '网卡呢', 答: '4235 个' });

  const 甲 = 我问过('ou_甲');
  eq(甲.length, 3, '我问过：只算真的问答（反馈那条没有「问」，不算）');
  真(!甲.some((x) => String(x.问).includes('乙问的')), '我问过：**一条别人的都没有**（不按人切=一句话翻出全公司的）');
  eq(甲[0].问, '网卡呢', '我问过：最近的排最前（人翻记录都是先看最近的）');
  真(甲.some((x) => x.出错), '我问过：**出错的那条也要列**（它答不出来的那次最该被看见）');
  eq(我问过('ou_从没问过的人').length, 0, '我问过：没问过就是空');
  eq(我问过('').length, 0, '我问过：空 sender 回空（不许当成「全都要」）');
  eq(我问过('ou_甲', { 几条: 2 }).length, 2, '我问过：几条管用');
}
{
  const { 历史正文 } = await import('../lib/护栏.mjs');
  eq(历史正文([]), '你最近（两个月内）没在这儿问过什么。', '历史正文：空的时候说人话');
  const 话 = 历史正文([
    { 时刻: '2026-08-23 14:05:01', 问: '光模块还有多少', 答: '闵行 85093 根', 用了: ['查库存'], 总毫秒: 3200 },
    { 时刻: '2026-08-23 13:00:00', 问: '通算多少台', 出错: '连不上内网CMDB' },
  ]);
  真(话.includes('08-23 14:05'), '历史正文：时间只到分（秒没用，占地方）');
  真(话.includes('查库存') && 话.includes('3.2s'), '历史正文：带上用了什么工具、花了多久');
  真(话.includes('那次出错了'), '历史正文：出错的那条明说出错，不装成答案');
  真(话.includes('只有你自己的'), '历史正文：明说范围（别让人以为翻的是全群）');
}

console.log(`\n检查了 ${n} 条判据，失败 ${挂}`);
process.exit(挂 ? 1 : 0);
