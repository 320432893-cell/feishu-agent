/**
 * 对话压缩测试。守的是三件事：
 *  ① 该压才压（没满不许动，压了就是白花一次模型调用）
 *  ② **压失败要退回原样**，绝不能把已经攒下的摘要冲掉（越压越忘是这类功能最容易犯的错）
 *  ③ 旧摘要必须带进下一次压缩，不然压第二次就把第一次的忘了
 * 假的「问模型」，不打网，只认退出码。
 */
import { 轮数, 该压吗, 摘要提示, 压一次, 摘要消息, 压完怎么写 } from '../lib/对话摘要.mjs';

let 挂 = 0, n = 0;
const eq = (得, 期, 说) => { n++; if (JSON.stringify(得) !== JSON.stringify(期)) { 挂++; console.log(`✗ ${说}｜得 ${JSON.stringify(得)} 期 ${JSON.stringify(期)}`); } else console.log(`✓ ${说}`); };
const 真 = (得, 说) => eq(!!得, true, 说);

const 造 = (n) => Array.from({ length: n * 2 }, (_, i) => (i % 2 === 0
  ? { role: 'user', content: `第${Math.floor(i / 2) + 1}问` }
  : { role: 'assistant', content: `第${Math.floor(i / 2) + 1}答` }));

// —— ① 该压才压 ——
eq(轮数(造(5)), 5, '轮数：一问一答算一轮');
eq(该压吗(造(4), 6).压.length, 0, '该压吗：没到保留轮数，一条都不压');
eq(该压吗(造(4), 6).留.length, 8, '该压吗：没到就原样带走');
{
  const { 留, 压 } = 该压吗(造(10), 6);
  eq(留.length, 12, '该压吗：超了 → 留最近 6 轮');
  eq(压.length, 8, '该压吗：超出的 4 轮拿去压');
  eq(压[0].content, '第1问', '该压吗：**压的是最老的那几轮**');
  eq(留[0].content, '第5问', '该压吗：留的是最近的');
  eq([...压, ...留].length, 20, '该压吗：留+压 = 原样，一条不丢（丢了就是悄悄少了上下文）');
}
eq(该压吗([], 6).压.length, 0, '该压吗：空历史不炸');
eq(该压吗(null, 6).留.length, 0, '该压吗：null 不炸');

// —— ③ 旧摘要要带进提示，否则压第二次就忘了第一次 ——
{
  const 提示 = 摘要提示('他关心的是临港那批，口径按在库', 造(2));
  真(提示.includes('临港那批'), '摘要提示：**旧摘要带进去了**（不带=压一次忘一次，越压越忘）');
  真(提示.includes('第1问'), '摘要提示：这次要压的对话也在里面');
  真(提示.includes('别写"他问了什么我答了什么"这种流水账'), '摘要提示：明说别写流水账（流水账占字数又没用）');
  真(!摘要提示('', 造(1)).includes('之前已经攒下'), '摘要提示：没有旧摘要时不塞那一段空标题');
}

// —— ② 压失败退回原样，绝不冲掉旧摘要 ——
{
  const 旧 = '他关心的是临港那批';
  eq(await 压一次({ 问模型: async () => { throw new Error('模型挂了'); }, 模型配置: {}, 旧摘要: 旧, 要压的: 造(3) }), 旧,
    '压一次：**模型挂了就退回旧摘要**（退回「丢掉老的」，也就是没这功能时的行为）');
  eq(await 压一次({ 问模型: async () => ({ content: '   ' }), 模型配置: {}, 旧摘要: 旧, 要压的: 造(3) }), 旧,
    '压一次：空回复也算没压成，不许把旧摘要冲成空');
  eq(await 压一次({ 问模型: async () => ({ content: '新要点' }), 模型配置: {}, 旧摘要: 旧, 要压的: [] }), 旧,
    '压一次：没东西要压就别调模型（白花 2-4 秒）');
}
{
  let 调了几次 = 0;
  const r = await 压一次({ 问模型: async () => { 调了几次++; return { content: '临港那批，在库口径，光模块 119582' }; }, 模型配置: {}, 旧摘要: '旧的', 要压的: 造(3) });
  eq(r, '临港那批，在库口径，光模块 119582', '压一次：压成了就用新的');
  eq(调了几次, 1, '压一次：只调一次模型');
  const 长 = await 压一次({ 问模型: async () => ({ content: '甲'.repeat(2000) }), 模型配置: {}, 要压的: 造(3), 上限字: 600 });
  eq(长.length, 600, '压一次：模型写太长要截，别让摘要自己变成新的上下文负担');
}

// —— max_tokens 要给思考留够 + 空回复必须喊 ——
// 2026-08-22 真踩的：第一版 max_tokens 设 800，模型光思考就吃掉全部预算、正文一个字没剩，
// 于是「悄悄退回旧摘要」——功能没工作而日志一片祥和。这两条盯着它别再发生。
{
  let 收到的额外 = null;
  await 压一次({ 问模型: async (a) => { 收到的额外 = a.额外; return { content: 'ok' }; }, 模型配置: {}, 要压的: 造(3) });
  真(收到的额外?.max_tokens >= 2000,
    `摘要预算：max_tokens 至少 2000（现在 ${收到的额外?.max_tokens}）—— 这个模型光思考就要 600-1500，给少了会回空串`);
}
{
  // 空回复要在 stderr 喊一声，而且要带上 finish/usage —— 不然下次还是查不出为什么空
  const 原写 = process.stderr.write.bind(process.stderr);
  let 喊了 = '';
  process.stderr.write = (s) => { 喊了 += s; return true; };
  const r = await 压一次({
    问模型: async () => ({ content: '', _finish: 'length', _usage: { completion_tokens: 800, completion_tokens_details: { reasoning_tokens: 800 } } }),
    模型配置: {}, 旧摘要: '旧的', 要压的: 造(3),
  });
  process.stderr.write = 原写;
  eq(r, '旧的', '空回复：退回旧摘要（不冲掉）');
  真(喊了.includes('[压缩]'), '空回复：**要喊一声** —— 悄悄退回=功能坏了而日志一片祥和');
  真(喊了.includes('length'), '空回复：喊的时候带上 finish_reason（length 就是 max_tokens 给小了）');
  真(喊了.includes('800'), '空回复：带上烧了多少 token、其中多少是思考');
}

// —— 压完之后往回写：两个坑都只在「压缩那几秒里又来了一条」时出现，手点撞不出来 ——
{
  const 现 = { 历史: 造(8), 摘要: '旧的', ts: 1 };
  const 写 = 压完怎么写(现, { 保留轮: 6, 旧摘要: '旧的', 新摘要: '新的' });
  eq(写.摘要, '新的', '压完写回：正常情形，摘要换成新的');
  eq(写.历史.length / 2, 6, '压完写回：**这时候才砍到 6 轮** —— 砍早了那几轮在历史和摘要里都不在');
  eq(写.ts, 1, '压完写回：不动 ts（压缩不算一次新的对话，不该续命）');
}
eq(压完怎么写(null, { 保留轮: 6, 旧摘要: '', 新摘要: 'x' }), null,
  '压完写回：这期间上下文过期没了 → 不写（写回去=让过期的上下文复活）');
eq(压完怎么写({ 历史: 造(8), 摘要: '别人压出来的' }, { 保留轮: 6, 旧摘要: '旧的', 新摘要: '我的' }), null,
  '压完写回：**这期间别人已经压过一轮 → 不写**（不然拿我这份旧的盖掉更新的）');
{
  // 压失败（新摘要===旧摘要）也必须砍 —— 不砍的话一次压不成，历史就永远涨下去
  const 写 = 压完怎么写({ 历史: 造(9), 摘要: '旧的' }, { 保留轮: 6, 旧摘要: '旧的', 新摘要: '旧的' });
  eq(写.历史.length / 2, 6, '压完写回：**压失败也要砍**（退回「丢掉老的」，但不能不砍）');
}

// —— 摘要怎么塞回去 ——
eq(摘要消息(''), null, '摘要消息：没摘要就不塞空消息进 messages');
eq(摘要消息('   '), null, '摘要消息：全空格也算没有');
{
  const m = 摘要消息('临港那批，在库口径');
  eq(m.role, 'system', '摘要消息：以 system 身份塞，别冒充同事说过的话');
  真(m.content.includes('临港那批'), '摘要消息：内容在里面');
}

console.log(`\n检查了 ${n} 条判据，失败 ${挂}`);
process.exit(挂 ? 1 : 0);
