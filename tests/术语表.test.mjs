/**
 * 术语表测试：口令认得准、冲突不静默覆盖、空表不塞噪音。只认退出码、不打网。
 * 最要紧的两条：**普通问话绝不能被当成口令**（那样人问一句话就把术语表改了），
 * 以及**同名冲突不许悄悄覆盖**（术语表影响所有人的查询结果）。
 */
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const 临 = mkdtempSync(join(tmpdir(), 'bot-glossary-'));
process.env.BOT_GLOSSARY = join(临, '术语表.json');
const { 加术语, 改术语, 删术语, 列术语, 术语段, 认口令 } = await import('../lib/术语表.mjs');

let 挂 = 0, n = 0;
const eq = (得, 期, 说) => { n++; if (得 !== 期) { 挂++; console.log(`✗ ${说}｜得 ${JSON.stringify(得)} 期 ${JSON.stringify(期)}`); } else console.log(`✓ ${说}`); };
const 真 = (得, 说) => eq(!!得, true, 说);

// —— 空表不塞噪音 ——
eq(术语段(), '', '空表：拼给模型的是空串，不塞「（暂无术语）」那种废话');

// —— 加 / 读 ——
真(加术语('通算', 'CPU 机（机型:CPU）', 'ou_1').加了, '加：第一条进得去');
真(加术语('b300', '算300', 'ou_1').加了, '加：第二条');
eq(列术语().length, 2, '读：两条都在');
真(列术语()[0].谁 === 'ou_1' && 列术语()[0].何时, '加：记下了谁加的、什么时候（出错时能追是谁教的）');
真(术语段().includes('通算 = CPU 机'), '拼给模型的那段里有这条');

// —— 冲突不静默覆盖 ——
eq(加术语('通算', 'CPU 机（机型:CPU）', 'ou_2').一样, true, '同名同义：认成「一样」，不重复加');
const 冲 = 加术语('通算', '别的意思', 'ou_2');
eq(冲.冲突, 'CPU 机（机型:CPU）', '**同名不同义：报冲突并给出原释义，绝不悄悄覆盖**');
eq(列术语().length, 2, '冲突时表没被改');
真(改术语('通算', '别的意思', 'ou_2').改了, '人确认之后才走「改」这条路');
eq(列术语().find((x) => x.词 === '通算').释义, '别的意思', '改完生效');

// —— 删 ——
真(删术语('b300').删了, '删：删得掉');
真(删术语('根本没有这条').没这条, '删：没有的那条明说，不假装成功');
eq(列术语().length, 1, '删完只剩一条');

// —— 口令：认得准 ——
eq(认口令('记住：通算就是CPU机')?.词, '通算', '口令：记住 X 就是 Y');
eq(认口令('记住：通算就是CPU机')?.释义, 'CPU机', '口令：释义取对');
eq(认口令('记下 b300 = 算300')?.词, 'b300', '口令：等号写法也认');
eq(认口令('改成：通算 = 别的意思')?.动作, '改', '口令：改成（冲突时人再明说一次才动）');
eq(认口令('改成：通算 = 别的意思')?.词, '通算', '口令：改成 —— 词取对');
eq(认口令('忘掉 通算')?.动作, '删', '口令：忘掉');
eq(认口令('看术语')?.动作, '列', '口令：看术语');

// —— **重点：普通问话绝不能被当成口令** ——
for (const 句 of [
  '光模块库存还有多少',
  '通算和存储各多少台',
  '看下 h3c 的交换机数量',
  '这批 SN 是哪些订单的',
  '把这张表的型号列对齐一下内网CMDB',
]) {
  eq(认口令(句), null, `口令：「${句}」是普通问话，不许当成改术语表`);
}

rmSync(临, { recursive: true, force: true });
console.log(`\n检查了 ${n} 条判据，失败 ${挂}`);
process.exit(挂 ? 1 : 0);
