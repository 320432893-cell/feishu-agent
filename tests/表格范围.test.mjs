// —— 「剩下」：链接旁边还有没有实质的话 ——
// 2026-08-24 真事：「SP4交换机 10 … 匹配下交换机 <链接>」被整个当成设范围口令，
// 设完范围回一张「已限定」卡片就 return，**那句要匹配的话一个字都没进模型**。
// 人看到的是答非所问 → 点解除 → 重发 → 又被吃一次。调用方靠 `剩下` 分这两种。
{
  // ① 纯口令：抠掉链接和参数之后基本不剩什么 → 照旧只回执、不往下答
  真((认范围口令(`只看这张：${A}`).剩下 || '').length < 8, '剩下：「只看这张：<链接>」是纯口令，剩不下东西');
  真((认范围口令(`表 ${A} sheet 转固清单 表头 51 列 型号,数量`).剩下 || '').length < 8,
    '剩下：**参数写全的那种也是纯口令** —— sheet/表头/列 都得抠掉，不然会被当成问题');
  真((认范围口令(`${A} sheet=转固清单 表头行=51\n${B} sheet=对照 表头=1`).剩下 || '').length < 8,
    '剩下：两行两张表、参数写全，照样是纯口令');

  // ② 带着表来问问题：必须剩下一大截，调用方据此接着答
  const 真问 = 认范围口令(`SP4交换机 10 TD3-10G 交换机 1 TD3-25G 交换机 1 TH4-400G 交换机 1匹配下交换机${A}去找个表`);
  真(真问.设.length === 1, '剩下：带问题的消息照样把表认出来（范围还是要设的）');
  真(真问.剩下.length >= 8 && 真问.剩下.includes('SP4交换机'),
    `剩下：**问题部分留得住**，调用方才知道不能吞 —— 实际剩「${真问.剩下.slice(0, 40)}」`);
  真(!真问.剩下.includes('http'), '剩下：链接本身不许留在里面（留着会让门槛永远够）');

  const 真问2 = 认范围口令(`${A} 帮我把型号列跟内网CMDB对一下，看多少对得上`);
  真(真问2.剩下.length >= 8, '剩下：链接在前、问题在后也认（只验一种写法等于没验）');
}

// —— 参数名前面必须是分隔边界 ——
// 2026-08-24 实测的既有 bug：「型号**列**跟内网CMDB对一下」里那个「列」被当成参数名，
// 解析出 `列:["跟内网CMDB对一下","看多少对得上"]` → `读表数据` 只去读两个不存在的列，
