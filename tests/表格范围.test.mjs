  eq(认范围口令(`表 ${A} sheet 转固清单 表头 51 列 型号,数量`).设[0].列, ['型号', '数量'], '边界：写全的那种照旧认');
  eq(认范围口令(`表 ${A} sheet 转固清单 表头 51`).设[0].表头行, 51, '边界：`表头 51` 照旧认（别把参数一起误伤）');
