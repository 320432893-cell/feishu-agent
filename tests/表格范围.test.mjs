/**
 * 范围锁测试。守的一件事：**人指定了哪张表，模型就不许读别的**。
 * 跑偏的代价在这儿特别实 —— 它读了别的 sheet、拿别的表的列去匹配，
 * 答案照样成句、数字照样有，**没有任何东西会红**，人拿去对账才发现对的是另一张表。
 * 所以这是闸不是嘱咐：正向（该放的放、该补的补）和反向（该拦的拦）都要验。
 */
import { 取表token, 同一张表, 卡范围, 范围段, 表格工具, 认范围口令, 范围回执, 范围表单卡, 表单转范围, 设范围按钮名 } from '../lib/表格范围.mjs';

let 挂 = 0, n = 0;
const eq = (得, 期, 说) => { n++; if (JSON.stringify(得) !== JSON.stringify(期)) { 挂++; console.log(`✗ ${说}｜得 ${JSON.stringify(得)} 期 ${JSON.stringify(期)}`); } else console.log(`✓ ${说}`); };
const 真 = (得, 说) => eq(!!得, true, 说);

const A = 'https://example.feishu.cn/sheets/SHEETTOKENBBBBBBBBBBBBBBBBB';
const A带参 = 'https://example.feishu.cn/sheets/SHEETTOKENBBBBBBBBBBBBBBBBB?sheet=ELacW0';
const B = 'https://example.feishu.cn/sheets/OtherTokenAAAAAAAAAAAAAAAAA';
const wiki = 'https://example.feishu.cn/wiki/SHEETTOKENBBBBBBBBBBBBBBBBB';

// —— 抠 token ——
eq(取表token(A), 'SHEETTOKENBBBBBBBBBBBBBBBBB', 'token：sheets 链接');
eq(取表token(A带参), 'SHEETTOKENBBBBBBBBBBBBBBBBB', 'token：**带查询参数不影响**（?sheet= 是常见形态）');
eq(取表token(wiki), 'SHEETTOKENBBBBBBBBBBBBBBBBB', 'token：wiki 链接');
eq(取表token('SHEETTOKENBBBBBBBBBBBBBBBBB'), 'SHEETTOKENBBBBBBBBBBBBBBBBB', 'token：直接贴 token 也认');
eq(取表token('随便一句话'), '', 'token：抠不出就是空串');
真(同一张表(A, A带参), '同一张表：带不带参数算同一张');
eq(同一张表(A, B), false, '同一张表：不同 token 不算');
eq(同一张表('', A), false, '同一张表：空的不算（别让空 url 蒙混过关）');

const 范围 = { url: A, sheet名: '转固清单', 表头行: 51, 列: ['C', 'D'] };

// —— 反向：读别的表必须拦 ——
{
  const r = 卡范围('读表数据', { url: B }, 范围);
  真(r.拦, '**拦：读别的表**（这是「发散到别的表」唯一真正危险的形态）');
  真(r.说明.includes('别换表'), '拦：说明里明说别换表，不是一句「不许」');
  真(r.说明.includes('如实告诉用户'), '拦：给了下一步怎么办（不然它会一直重试）');
}
{
  const r = 卡范围('读表数据', { url: A, sheet名: '增配设备' }, 范围);
  真(r.拦, '**拦：换 sheet**（换 sheet 和换表一样会把答案对到别处）');
  真(r.说明.includes('转固清单'), '拦：说明里带着人指定的那张 sheet 名');
}
{
  const r = 卡范围('读飞书表', { url: A, sheet序号: 2 }, 范围);
  真(r.拦, '拦：**指定了 sheet 名还用序号另挑一张**（绕过 sheet名 检查的口子）');
}

// —— 正向：该放的放、该补的补 ——
{
  const r = 卡范围('读表数据', {}, 范围);
  真(r.放行, '放行：没给 url');
  eq(r.参数.url, A, '补：url 补成锁定的那张（模型省略参数是常事，补比拒省一轮）');
  eq(r.参数.sheet名, '转固清单', '补：sheet 名补上');
  eq(r.参数.range, 'A51:BZ451', '补：**表头行顶到 range 起点** —— 四个字段里最值钱的一个');
  eq(r.参数.列, ['C', 'D'], '补：只取指定的列');
}
{
  const r = 卡范围('读表数据', { url: A带参, sheet名: '转固清单', range: 'A51:R120' }, 范围);
  真(r.放行, '放行：指对了表和 sheet');
  eq(r.参数.range, 'A51:R120', '不覆盖：模型自己给了 range 就用它的（它可能圈得更准）');
}
{
  const r = 卡范围('读表数据', { url: A, sheet名: '转固' }, 范围);
  真(r.放行, '放行：sheet 名是**包含匹配**（人写全称、模型写简称，不该拦）');
}

