/**
 * 对话压缩：**轮数满了不是把老的扔掉，而是先攒成一段摘要再扔。**
 *
 * 为什么要它：追问的上文原来是「最近 N 轮，超了直接丢」。同事连着问五六句、
 * 或者中间隔了一会儿再回来，最早那句定调的话（「我说的是临港那批」「按在库口径」）就没了，
 * 而模型不会说"我忘了"，它会**按默认口径接着答**——错得毫无征兆。
 *
 * **为什么不是"多留几轮就行"**：多留确实几乎不花钱（实测输入 12486 token 在一条 4.7 秒的查询里
 * 占比很小，上限是 288954），所以第一档就是把轮数和时间窗调大。但轮数再大也是个数，
 * 满了还是要丢；摘要管的是「丢掉的那些里有没有还在起作用的前提」。
 *
 * **压缩这一步不许让人等**：它是一次额外的模型调用（2-4 秒）。所以由调用方在**答复发出之后**
 * 再跑，压失败就保持原样（退回「丢掉老的」，也就是今天的行为），绝不影响这一轮的回答。
 */

/** 一轮 = 一问一答两条。 */
export const 轮数 = (历史) => Math.floor((历史 || []).length / 2);

/**
 * 该不该压：历史超过保留轮数就该。
 * @returns {留, 压} —— 留=接着带走的那几轮，压=要折进摘要的那几轮（空数组表示不用压）
 */
export function 该压吗(历史, 保留轮 = 6) {
  const h = (历史 || []).filter((m) => m && m.role && m.content);
  const 保留条 = 保留轮 * 2;
  if (h.length <= 保留条) return { 留: h, 压: [] };
  return { 留: h.slice(-保留条), 压: h.slice(0, h.length - 保留条) };
}

/** 拼给模型的那段提示。单独拆出来是为了能离线验它有没有把旧摘要带上（丢了旧摘要=越压越忘）。 */
export function 摘要提示(旧摘要, 要压的) {
  const 对话 = 要压的.map((m) => `${m.role === 'user' ? '同事' : '我'}：${String(m.content).slice(0, 500)}`).join('\n');
  return '把下面这段飞书群里的问答压成不超过 200 字的要点，供我接着往下答。\n'
    + '**只留还会影响后续回答的东西**：他关心的范围（哪个库房/哪批订单/哪个项目）、'
    + '他认过的口径、已经查出来的关键数字、他纠正过我的地方。\n'
    + '**别写"他问了什么我答了什么"这种流水账**，别复述完整答案，别加客套。查完就没用的细节直接扔。\n'
    + (旧摘要 ? `\n【之前已经攒下的要点，一并合进去、别丢】\n${旧摘要}\n` : '')
    + `\n【这次要压的对话】\n${对话}`;
}

/**
 * 压一次。**失败返回旧摘要**（退回「丢掉老的」，也就是没有这个功能时的行为），不抛。
 * @param 问模型 传进来而不是 import —— 这样测试能拿假的，离线跑。
 */
export async function 压一次({ 问模型, 模型配置, 旧摘要 = '', 要压的 = [], 上限字 = 600 }) {
  if (!要压的.length) return 旧摘要;
  try {
    const msg = await 问模型({
      ...模型配置,
      messages: [{ role: 'user', content: 摘要提示(旧摘要, 要压的) }],
      // **max_tokens 要给思考留够**。第一版设 800，实测直接回空串：这个模型光思考就要
      // 600-1500 token（47 字的答案烧过 649 token、其中 622 是思考），800 全被思考吃光、
      // 一个字正文都没剩下。摘要正文只要 200 字，但预算得按「思考+正文」给。
      额外: { max_tokens: 2500 },
    });
    const 文 = String(msg?.content || '').trim();
    if (!文) {
      // **空回复必须喊一声**。不喊的话表现是「悄悄退回旧摘要」——功能没工作，而日志一片祥和，
      // 正是今天修了一整天的那类毛病。我自己在这儿又犯了一次（max_tokens 给小了），
      // 就是因为第一版这里直接 return、什么都没说。
      process.stderr.write('[压缩] **模型没吐出摘要**（'
        + `finish=${msg?._finish} 输出 ${msg?._usage?.completion_tokens ?? '?'} token，`
        + `其中思考 ${msg?._usage?.completion_tokens_details?.reasoning_tokens ?? '?'}）——保持原样。`
        + 'finish=length 就是 max_tokens 给小了，被思考吃光了。\n');
      return 旧摘要;
    }
    return 文.slice(0, 上限字);
  } catch (e) {
    process.stderr.write(`[压缩] 压不动：${String(e.message).slice(0, 100)} —— 保持原样\n`);
    return 旧摘要;
  }
}

/**
 * 压缩回来之后，该往上下文里写什么。**单独拎成纯函数就是为了能离线验** ——
 * 这里两个坑都只在「压缩那几秒里又来了一条」时才出现，靠手点根本撞不出来。
 *
 * @param 现 现在存着的那条（`上下文.get(key)`），可能已经过期没了、也可能被别的查询改过
 * @returns 要写回去的新记录；返回 null = 这次别写
 */
export function 压完怎么写(现, { 保留轮, 旧摘要, 新摘要 }) {
  if (!现) return null;                 // 这期间过期了 —— 写回去等于让过期的上下文复活
  if (现.摘要 !== 旧摘要) return null;   // 这期间别人已经压过一轮 —— 别拿我这份旧的盖掉更新的
  // **无论压成没压成都要砍到「留」**：压成了有摘要顶着；没压成就退回「丢掉老的」（今天以前的行为）。
  // 不砍的话历史会一直涨，一次压不成就永远涨下去。
  return { ...现, 历史: 该压吗(现.历史, 保留轮).留, 摘要: 新摘要 };
}

/** 把摘要拼成一条能塞进 历史 前面的消息；没摘要就返回 null（别塞空消息进去）。 */
export function 摘要消息(摘要) {
  if (!摘要 || !String(摘要).trim()) return null;
  return { role: 'system', content: `【这位同事之前聊过的要点，接着往下答时按这些理解】\n${String(摘要).trim()}` };
}
