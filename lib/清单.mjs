/**
 * **一次查询要办好几件事时，把它们记成一张清单。**
 *
 * 为什么要它（三样，都不是"让模型更聪明"）：
 * ① **撞硬顶时能交半份。** 现在超时只回一句「卡住了」—— 2026-08-24 真事：一条 9 步的查询
 *    在第 8 步撞了 180 秒硬顶，前 7 步查到的东西**一个字都没给人**。有清单就能交
 *    「7 项做完 4 项，这 4 项是…」，人拿着这半份还能干活。
 * ② **交卷前查得出漏项。** 「有没有哪一项没查到」原来是提示词里的一句嘱咐，零强制；
 *    现在是一次 `没做完的()` 调用，答案里漏没漏是个能打印出来的数。
 * ③ **进度看得见。** 卡片上原来是「正在查 透视…（第 3 步）」——「第 3 步」不告诉人还剩多少。
 *
 * **不解决**「模型选错工具」，也不让它变快。它只保证**已经做完的事不会因为后面卡住而白做**。
 *
 * 按一次查询建一份（`建清单()`），不跨查询、不落盘 —— 进程没了那条查询本来就死了。
 */
export function 建清单() {
  /** @type {{文: string, 做完: boolean, 结果: string}[]} */
  let 条目 = [];

  return {
    /**
     * 记下要办的事。**再次调用是「合并」不是「重来」** —— 模型中途想起还有一项，
     * 直接重列一遍是最自然的写法，而覆盖式会把前面勾掉的状态全抹了
     * （表现是进度条倒退，人看着像机器在返工）。按 `文` 去重，老的保留状态。
     */
    记下(文们) {
      const 新的 = [];
      for (const f of (Array.isArray(文们) ? 文们 : [文们])) {
        const 文 = String(f ?? '').trim();
        if (!文) continue;
        if (条目.some((x) => x.文 === 文)) continue;
        条目.push({ 文, 做完: false, 结果: '' });
        新的.push(文);
      }
      return { 新增: 新的.length, 共: 条目.length };
    },

    /**
     * 勾掉第几条（1 开始）。**越界要报出来，不许静默忽略** ——
     * 静默的话「模型勾错了号」和「这条真办完了」在日志里长得一模一样，
     * 而进度会永远停在那儿，没有任何东西会红。
     */
    勾掉(序号们, 结果 = '') {
      const 好 = [], 坏 = [];
      for (const s of (Array.isArray(序号们) ? 序号们 : [序号们])) {
        const i = Number(s);
        if (!Number.isInteger(i) || i < 1 || i > 条目.length) { 坏.push(s); continue; }
        条目[i - 1].做完 = true;
        if (结果) 条目[i - 1].结果 = String(结果).slice(0, 200);
        好.push(i);
      }
      return { 勾掉了: 好, 越界: 坏, ...this.进度() };
    },

    进度() {
      return { 做完: 条目.filter((x) => x.做完).length, 共: 条目.length };
    },

    没做完的() {
      return 条目.filter((x) => !x.做完).map((x, ) => x.文);
    },

    有吗() { return 条目.length > 0; },

    条目们() { return 条目.map((x) => ({ ...x })); },

    /** 给卡片用的一小段，塞在「正在查 X…」后面。没条目就回空串（别给人看一个 0/0）。 */
    进度文() {
      const { 做完, 共 } = this.进度();
      return 共 ? `｜清单 ${做完}/${共}` : '';
    },

    /**
     * **撞硬顶/出错时交半份。** 这是这个模块存在的头号理由：
     * 把已经办完的那几项原样给人，没办的明说没办。没有清单就回空串（调用方退回原来那句话）。
     */
    交半份() {
      if (!条目.length) return '';
      const { 做完, 共 } = this.进度();
      const 行 = 条目.map((x, i) => (x.做完
        ? `✅ ${i + 1}. ${x.文}${x.结果 ? ` —— ${x.结果}` : ''}`
        : `⬜ ${i + 1}. ${x.文}（没查到这一步）`)).join('\n');
      return `**这条没跑完，但已经查到的先给你**（${共} 项做完 ${做完} 项）：\n${行}`;
    },

    /** 交卷前自查：还有没做完的就回一句话，全做完回空串。 */
    漏了吗() {
      const 剩 = this.没做完的();
      if (!剩.length) return '';
      return `清单里还有 ${剩.length} 项没勾掉：${剩.map((x) => `「${x}」`).join('、')}。`
        + '**要么去查完，要么在答案里明说这几项没查** —— 不许当它不存在。';
    },
  };
}
