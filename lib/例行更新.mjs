/**
 * 例行更新：日更 / 周更 / 导工单。**纯逻辑在这儿，接线在 bot.mjs。**
 *
 * 三个是**同一个形状**，所以合在一个模块：
 *   ① 人打口令（或定时器）→ ② 不带参调 = 干跑，回「回执 + 确认票」，一个字不写
 *   → ③ 卡片摆出回执 → ④ 人点「确认写入」→ 用**存下来的那份参数**重调才真写
 *
 * 形态和这个项目里别的写操作同构：**机器算、人按下去**。区别只在发起方 ——
 * `写占用` 是模型想写、被闸截住；这三个是**人自己发起或定时发起，模型全程碰不到这些工具**
 * （不在只读白名单、也不在写工具表里）。所以它们不受 `BOT_WRITE` 管：
 * 那个开关管的是「模型手上有没有写工具」，而这里模型手上根本没有。
 *
 * **模型只在「疑似改名」那一步出场**（日更/周更有，导工单没有），因为那是唯一真需要判断、
 * 也是唯一判错会留下烂账的地方：判成同款 → 两款货被并成一款；判成两款 → 老键归零而
 * 占用记录挂在上面悬空。所以模型只出判断和理由，**每一组连同「老键原在库多少根」摆到卡片上**。
 */

/**
 * 三件例行公事。加一件只要在这儿加一条 —— 口令、超时、判不判改名都在这里声明。
 * **`口令` 必须是整句锚定的**：「日更了吗」是问话不是命令，认错了会平白跑 30 秒。
 */
export const 例行们 = {
  日更: {
    名: '日更', 前缀: 'inv', 工具: '日更',
    口令: /^(日更|跑日更|日更一下|更新台账|台账日更)[！!。.]?$/,
    干跑毫秒: 120000, 真写毫秒: 180000, 判改名: true, 要内网: false,
    干跑说明: '从源表刷新台账、注册表、在途',
  },
  周更: {
    名: '周更', 前缀: 'inv', 工具: '周更',
    口令: /^(周更|跑周更|周更一下|周报)[！!。.]?$/,
    干跑毫秒: 200000, 真写毫秒: 240000, 判改名: true, 要内网: false,
    干跑说明: '日更的超集：和上周四那份基线比（周环比/哪些键真归零/在途到货没）',
  },
  导工单: {
    名: '导工单', 前缀: 'cmdb', 工具: '导工单',
    口令: /^(导工单|同步工单|拉工单|工单同步)[！!。.]?$/,
    干跑毫秒: 180000, 真写毫秒: 240000, 判改名: false, 要内网: true,
    干跑说明: '把内网CMDB的成本转移/采购工单增量同步进两张飞书台账表',
  },
};

/** 认例行口令。**整句锚定**，带别的字一律不认 —— 认岔了会平白跑半分钟还弹一张确认卡。 */
export function 认例行口令(文) {
  const s = String(文 || '').trim();
  for (const 配 of Object.values(例行们)) if (配.口令.test(s)) return 配;
  return null;
}

/**
 * **说得像但没说准的**（「日更下台账」「帮我跑个周更」），回一个按钮让人点一下。
 *
 * 2026-08-24 真踩到：整句锚定挡住了「日更了吗」这类问话，代价是**「日更下台账」也落空**，
 * 于是它落给模型 —— 而模型手上根本没有 `日更` 工具（这三件只在 bot 层），
 * 它就理直气壮地回「我跑不了日更流程，你去服务器上手动执行」。
 * **能力存在、人几乎说对了词、机器人却说做不到**，这比没有这个功能还糟。
 *
 * 不直接跑是因为**猜错的代价不对称**：多弹一个按钮，人不点就没事；
 * 猜着跑起来，人得等半分钟再看见一张他没要的确认卡。
 *
 * 问句一律不认（「日更了吗」「周更要多久」「导工单怎么用」）—— 那些交给模型答。
 */
const 像问句 = /[？?]|吗|呢|什么|怎么|多久|为什么|是啥|能不能|可以吗|结果|上次|之前/;
export function 认例行近似(文) {
  const s = String(文 || '').trim();
  if (!s || s.length > 30 || 像问句.test(s)) return null;
  if (认例行口令(s)) return null; // 强口令自己会跑，不走这条
  for (const 配 of Object.values(例行们)) if (s.includes(配.名)) return 配;
  // 「更新一下台账」「同步下工单」这类没直呼其名的
  if (/台账/.test(s) && /更新|刷新|跑一?下|跑个/.test(s)) return 例行们.日更;
  return null;
}

/** 干跑回包 → 结构化。解不出来返回 null（调用方要把原文摆出来，不许装作没事）。 */
export function 解干跑(回包) {
  let j;
  try { j = JSON.parse(String(回包)); } catch { return null; }
  if (!j || typeof j !== 'object' || !j.确认票) return null;
  return {
    确认票: String(j.确认票),
    回执: (j.回执 && typeof j.回执 === 'object') ? j.回执 : {},
    疑似改名: Array.isArray(j.疑似改名) ? j.疑似改名 : [],
    干跑自检红: Array.isArray(j.干跑自检红) ? j.干跑自检红 : [],
  };
}

/**
 * 给模型判改名用的提示。**判据是 MCP 自己在回执里写的那套**，不是我另编一套 ——
 * 两处各写一份的话，那边改了这边不知道，而错的那次没有任何东西会红。
 */
export function 改名提示(疑似改名) {
  const 组 = 疑似改名.map((x, i) => {
    const 差 = Array.isArray(x.差在哪) ? x.差在哪.join('；') : String(x.差在哪 || '');
    return `第 ${i + 1} 组\n  新键：${x.新键}\n  最像的老键：${x.最像的老键}\n  老键原在库：${x.老键原在库} 根\n  差在哪：${差}\n  接头尾巴：${x.接头尾巴 || '(无)'}`;
  }).join('\n\n');
  return '你在判「同一款货换了写法」还是「本来就是两款货」。键的格式是 `资产类型|品牌|通用型号|位置`。\n\n'
    + '**判据（照这个判，别自己发挥）**：\n'
    + '· 接头研磨代号换掉（PC / UPC / APC）→ **通常是同款换写法**\n'
    + '· 封装名的代际写法换掉（QSFP↔QSFP28、QSFPDD↔QSFP56DD、OSFP-RHS↔OSFP112-RHS）→ **通常是同款换写法**\n'
    + '· 介质波长后缀换掉（-MM850 / -SM1310 换成别的后缀）→ **通常是同款换写法**\n'
    + '· **速率不同、光学标准不同（SR4/DR4/LR4）、通道数不同 → 是两款货，绝不合并**\n'
    + '· 资产类型、品牌、位置这三段不一样 → 两款货\n\n'
    + `${组}\n\n`
    + '**只输出 JSON，别的一个字都不要**，形如：\n'
    + '{"判断":[{"第几组":1,"同款":true,"理由":"只差接头研磨代号 SM1310→UPC，速率光学标准通道数全同"}]}\n'
    + '每一组都要有一条。拿不准就填 `"同款":false`（不合并的代价是老键悬空、下次还会再问一遍；'
    + '合并错的代价是两款货被并成一款，改不回来）。';
}

/**
 * 模型回的文本 → `认定的改名` 数组。**只能从候选里挑，编的一律丢掉。**
 *
 * 这条是这个模块最要紧的判据：`认定的改名` 会直接决定哪两个物料键被合并，
 * 而模型完全有能力吐出一个候选里没有的键（拼错一个字、把「最像的老键」写成别的候选）。
 * 那样合并的就是另一对货，而**回执照样成句、数字照样有，没有任何东西会红**。
 *
 * @returns {{认定的改名: Array<{新键,老键}>, 判断: Array, 丢掉的: Array<string>}}
 */
export function 认改名判断(模型文本, 疑似改名) {
  const 候选 = new Map(疑似改名.map((x, i) => [i + 1, { 新键: String(x.新键 || ''), 老键: String(x.最像的老键 || ''), 老键原在库: x.老键原在库 }]));
  let j = null;
  // 模型爱在 JSON 外面裹 ```json 围栏或一句话，抠出第一个 {…} 再解
  const 文 = String(模型文本 || '');
  const 起 = 文.indexOf('{'); const 止 = 文.lastIndexOf('}');
  if (起 >= 0 && 止 > 起) { try { j = JSON.parse(文.slice(起, 止 + 1)); } catch { /* 解不出下面按空处理 */ } }
  const 原判 = Array.isArray(j?.判断) ? j.判断 : [];

  const 认定的改名 = []; const 判断 = []; const 丢掉的 = [];
  for (const 组 of 原判) {
    const 号 = Number(组?.第几组);
    const 候 = 候选.get(号);
    if (!候) { 丢掉的.push(`第 ${组?.第几组} 组：候选里没有这一组`); continue; }
    const 同款 = 组?.同款 === true;
    判断.push({ 第几组: 号, 新键: 候.新键, 老键: 候.老键, 老键原在库: 候.老键原在库, 同款, 理由: String(组?.理由 || '').slice(0, 200) });
    if (同款) 认定的改名.push({ 新键: 候.新键, 老键: 候.老键 }); // ← 键取自候选，不取自模型
  }
  // 模型漏判的组一律当「不合并」：漏了不许静默变成合并
  for (const [号, 候] of 候选) {
    if (判断.some((x) => x.第几组 === 号)) continue;
    判断.push({ 第几组: 号, 新键: 候.新键, 老键: 候.老键, 老键原在库: 候.老键原在库, 同款: false, 理由: '**模型没判这一组**，按不合并处理' });
    丢掉的.push(`第 ${号} 组：模型没判，按不合并`);
  }
  判断.sort((a, b) => a.第几组 - b.第几组);
  return { 认定的改名, 判断, 丢掉的 };
}

/**
 * 干跑回执 → 卡片上给人看的那段。**回执字段整个遍历，不写死字段名。**
 *
 * 写死的话，MCP 那边加一个字段（周更就比日更多「周环比/品牌待补/基线/源表/缺表」五个）
 * 这边**静默看不见** —— 而看不见的那个字段完全可能正是这次最要紧的信息。
 * 遍历的代价是顺序由对方定，那不重要；漏掉一个字段才重要。
 */
export function 回执正文(解出来的, 判断 = [], { 定时 = false, 名 = '更新' } = {}) {
  // 传进来 null 的时候**别炸**：调用方本来该先用 解干跑 的返回值判一次，
  // 但渲染卡片这一步炸掉的话，人看到的是「机器人卡住了」而不是「回包没认出来」——
  // 后者才是真相，而且是能查下去的那条线索。
  if (!解出来的) return `⚠ **${名}的干跑回包没认出来**（没有确认票），**什么都没写**。原文在日志里。`;
  const r = 解出来的.回执 || {};
  const 行 = [
    定时 ? `📅 **今天的${名}**（自动跑的干跑，还没写）` : `📅 **${名}干跑完了**（还没写）`,
    '',
  ];
  const 键们 = Object.keys(r);
  if (!键们.length) 行.push('· （回执是空的 —— 这不正常，下面的确认按钮先别点）');
  for (const k of 键们) {
    const v = r[k];
    行.push(`· ${k}：${typeof v === 'object' ? JSON.stringify(v).slice(0, 300) : String(v).slice(0, 300)}`);
  }
  if (解出来的.干跑自检红?.length) {
    行.push('', `⚠ **干跑自检报红 ${解出来的.干跑自检红.length} 条**：`);
    for (const x of 解出来的.干跑自检红.slice(0, 5)) 行.push(`  · ${String(x).slice(0, 160)}`);
  }
  if (判断.length) {
    行.push('', `**疑似改名 ${判断.length} 组**（我判过了，你看着数拍）：`);
    for (const x of 判断) {
      行.push(`${x.同款 ? '🔗' : '➖'} 第 ${x.第几组} 组：\`${x.新键}\``);
      行.push(`   ${x.同款 ? '**判为同款**，合并到' : '判为两款，不合并'} \`${x.老键}\`（老键原在库 **${x.老键原在库}** 根）`);
      行.push(`   ${x.理由}`);
    }
    行.push('', '**合并错了改不回来**；不合并的代价是老键那些占用记录悬空、下次还会再问一遍。');
  }
  return 行.join('\n');
}

/**
 * 定时配置。两种写法：
 *   `09:00`        每天
 *   `四 09:00`     每周四（一二三四五六日）
 * 解不出来的丢掉。**周更本来就只能周四跑**（它和上周四那份基线比），日期不是自由选项。
 */
const 星期字 = { 日: 0, 天: 0, 一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6 };
export function 解定时(文) {
  return String(文 || '').split(',').map((s) => s.trim()).filter(Boolean)
    .map((s) => {
      const m = /^(?:([日天一二三四五六])\s*)?(\d{1,2}):(\d{2})$/.exec(s);
      if (!m) return null;
      const 时 = Number(m[2]); const 分 = Number(m[3]);
      if (时 < 0 || 时 > 23 || 分 < 0 || 分 > 59) return null;
      return m[1] ? { 星期: 星期字[m[1]], 时, 分 } : { 时, 分 };
    })
    .filter(Boolean);
}

/**
 * 现在这一刻，该不该跑某个定时点。**按「本地年月日+时分」算一个标记**，
 * 跑过的标记记下来就不会重跑 —— 不靠定时器精度，也不怕进程重启后错过或重复。
 * @returns 该跑的标记，没有就 null
 */
export function 该跑吗(现在, 点们, 跑过) {
  const 年月日 = `${现在.getFullYear()}-${String(现在.getMonth() + 1).padStart(2, '0')}-${String(现在.getDate()).padStart(2, '0')}`;
  for (const p of 点们) {
    if (p.星期 !== undefined && 现在.getDay() !== p.星期) continue; // 指定了星期几就只在那天
    const 标记 = `${年月日} ${String(p.时).padStart(2, '0')}:${String(p.分).padStart(2, '0')}`;
    if (跑过.has(标记)) continue;
    // 到点了或者刚过（进程可能睡过去几分钟），但**不补跑一小时以前的** ——
    // 早上 9 点的日更，下午 3 点才补跑一次没有意义，数据早就变了。
    const 点时刻 = new Date(现在.getFullYear(), 现在.getMonth(), 现在.getDate(), p.时, p.分, 0).getTime();
    const 过了多久 = 现在.getTime() - 点时刻;
    if (过了多久 >= 0 && 过了多久 < 3600000) return 标记;
  }
  return null;
}

/** 定时点排成给人看的一句（帮助卡和开机日志都用）。 */
export function 定时说法(点们) {
  const 名 = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];
  return 点们.map((p) => `${p.星期 === undefined ? '每天' : `每${名[p.星期]}`} ${String(p.时).padStart(2, '0')}:${String(p.分).padStart(2, '0')}`).join('、');
}
