/**
 * 这次调用是不是「真的要写了」。**纯判断，给测试用。**
 * @returns true=要截住走人确认；false=还是干跑，放行
 */
export function 是真写吗(规矩, 参数) {
  if (!规矩) return false;
  if (规矩.人字段 !== undefined) return true;                       // 没有干跑这回事，每次都截
  if (规矩.真写开关) return 参数?.[规矩.真写开关] === true;
  if (规矩.票) return !!参数?.[规矩.票] && 参数?.[规矩.选择] === 规矩.真值;
  return false;
}

/** 单个工具回包喂给模型的字数上限。超了要留印（见下面派发处），不许静默砍。 */
const 回包上限 = Number(process.env.AGENT_TOOL_RESULT_MAX || 20000);
/**
 * 一条查询最多几轮。**2026-08-24 从 8 抬到 20。**
 *
 * 8 是当初为「群里不能让人干等」定的，而那个前提在 2026-08-20 加了流式卡片和
 * onStep「🔍 正在查 X…」之后就变了——进度现在是可见的，人看得见它在动。
 *
 * 本地留存 26 条答复里**一次都没撞过 8 轮**（最高 4 轮，收敛=false 为 0），
 * 所以这条对现有负载是零收益；抬它是为了那类真需要多步的活（对照 WorkBuddy
 * 同类工作负载：19.3% 超过 8 轮，最长 53 轮）。
 *
 * **为什么是 20 不是 25**：要和 回包上限 一起算。20×20000×0.8 ≈ 32 万 token，
 * 已经超过上下文上限 288,954，靠 压上下文 在 75% 处兜底（挪走最老的工具回包、留标记）。
 * 再往上抬会让压缩从中段就开始触发，**查到后面时前面几轮的证据已经不在上下文里了** ——
 * 那是比「答不出来」更难查的错：答案照样成句，只是它没看见早先那批数据。
 */
const 轮数上限 = Number(process.env.AGENT_MAX_ROUNDS || 20);

/**
 * 上下文预算。**撞上去是硬错、没有任何退路**：网关回 400 `context_length_exceeded`，
 * fallback 会拿同一堆 messages 去问下一个模型、同样撞、最后变成群里一句「所有模型都失败」。
 *
 * 2026-08-22 实测这个网关：**上限 288954 token**（60 万字的请求被拒，错误里写着
 * "Input length (360012 tokens) exceeds the maximum allowed length (288954 tokens)"）。
 * 真实一条查询的输入是 12486 token，最坏情况（8 轮 × 6000 字回包）约 4 万 —— 只用到 14%。
 * 所以这道闸**平时不会响**，它管的是「回包上限被调大」「读表数据拉回一整列」这类往上顶的情况。
 *
 * 字→token 的比例也是实测的，别拍脑袋：中文散文 0.778、真工具回包（中文+JSON）0.574、
 * 纯 JSON 0.415 token/字。这里取 **0.8**（比最贵的那类还高一点）—— 估高了只会压得早一点，
 * 估低了会直接撞墙，两种错的代价不对等。
 */
const 上下文上限 = Number(process.env.AGENT_CONTEXT_TOKENS || 288954);
const 压缩线 = 上下文上限 * Number(process.env.AGENT_CONTEXT_RATIO || 0.75);
const 每字token = 0.8;
const 估token = (messages) => Math.round(messages.reduce((s, m) => s + String(m.content || '').length
  + (m.tool_calls ? JSON.stringify(m.tool_calls).length : 0), 0) * 每字token);

/**
 * 快满了就把**最老的工具回包**挪出去，从老到新，一条一条挪到降下来为止。
 * 挪掉的位置留一句话（不是删掉整条消息）——`tool_call_id` 必须还在，
 * 少一条 API 直接报「tool_calls 没有对应的 tool 回复」。
 * @returns 挪了几条
 */
function 压上下文(messages) {
  let 挪了 = 0;
  for (const m of messages) {
    if (估token(messages) <= 压缩线) break;
    if (m.role !== 'tool' || String(m.content || '').startsWith('〔已挪出上下文')) continue;
    const 原长 = String(m.content || '').length;
    m.content = `〔已挪出上下文：这条工具回包原有 ${原长} 字，因为上下文快满了被移走。`
      + `**别对它的内容下结论**——还需要的话重新查一次，或者缩小范围再查。〕`;
    挪了++;
  }
  return 挪了;
}

