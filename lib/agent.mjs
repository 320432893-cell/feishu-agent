function 转函数(前缀, 工具) {
  const 补 = 工具补充说明[工具.name];
  return {
    type: 'function',
    function: {
      name: `${前缀}_${工具.name}`,
      description: (工具.description || '').slice(0, 900) + (补 ? `\n\n${补}` : ''),
      parameters: 工具.inputSchema || { type: 'object', properties: {} },
    },
  };
}

